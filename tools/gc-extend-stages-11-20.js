function targetGarbageCount(chapterIndex, localIndex) {
    const themeVariation = ((chapterIndex * 3 + localIndex) % 5) - 2;
    return Math.max(35, Math.min(64, CHAPTER_10_GARBAGE_PLAN[localIndex] + themeVariation));
}

function rowsFromManualGrid(definition, stageId) {
    if (!definition || !Array.isArray(definition.lines)) throw new Error('缺少手工布局：' + stageId);
    const start = Number(definition.topRow) - 1;
    if (start < 4 || start + definition.lines.length > 20) throw new Error('手工布局越界：' + stageId);
    const rows = {};
    definition.lines.forEach((line, index) => {
        if (!/^[.#]{10}$/.test(line) || line === '##########') throw new Error('手工布局非法：' + stageId);
        if (line.indexOf('#') >= 0) rows[String(start + index)] = line;
    });
    return rows;
}

function rowsFromProfile(profile, stageId, variant, targetTopRow, targetGarbageCount) {
    if (!/^\d{10}$/.test(profile)) throw new Error('非法高度谱：' + profile);
    const heights = profile.split('').map(Number);
    // 保留一侧直通顶部的入口，禁止底行成为开局即满的垃圾行。
    // 同高边缘按关卡奇偶交替，避免所有轮廓机械地向同一侧开口。
    const opening = heights[0] < heights[9] ? 0
        : heights[9] < heights[0] ? 9 : (stageId % 2 ? 0 : 9);
    heights[opening] = 0;

    // 非线性向上拉伸轮廓：最高点达到计划行，低矮边缘尽量留在下方。
    // 这样不会把整块图案粗暴整体抬高，仍能辨认原来的主题剪影。
    const sourceMax = Math.max.apply(null, heights);
    const targetMax = 21 - targetTopRow;
    const delta = targetMax - sourceMax;
    if (delta < 0) throw new Error('目标高度低于原轮廓：' + stageId);
    const peaks = heights.map((height, column) => height === sourceMax ? column : -1).filter((column) => column >= 0);
    const peak = peaks[stageId % peaks.length];
    for (let c = 0; c < heights.length; c++) {
        if (!heights[c]) continue;
        const ratio = heights[c] / sourceMax;
        heights[c] += Math.round(delta * 0.1 * ratio * ratio * ratio * ratio);
    }
    heights[peak] = targetMax;
    // 仅在基础轮廓碰撞时抬高少量内部轮廓点，保持主题主体不变并保证每关唯一。
    for (let i = 0; i < (variant || 0); i++) {
        const c = 1 + ((stageId + i * 3) % 8);
        heights[c] = Math.min(targetMax, heights[c] + 1);
    }

    // 贴近第 10 章同一关位的垃圾总量（主题间仅允许 ±2 块微差）。削减时保留入口与最高尖峰，
    // 从其余高列逐层收薄；补足时只补低列，避免改变最高垃圾行。
    const garbageCount = () => heights.reduce((sum, height) => sum + height, 0);
    while (garbageCount() > targetGarbageCount) {
        const candidates = heights
            .map((height, column) => ({ height, column }))
            .filter((item) => item.column !== opening && item.column !== peak && item.height > 1)
            .sort((a, b) => b.height - a.height
                || ((a.column + stageId + variant * 3) % 10) - ((b.column + stageId + variant * 3) % 10));
        if (!candidates.length) throw new Error('无法压缩垃圾数量：' + stageId);
        heights[candidates[0].column]--;
    }
    while (garbageCount() < targetGarbageCount) {
        const candidates = heights
            .map((height, column) => ({ height, column }))
            .filter((item) => item.column !== opening && item.column !== peak && item.height < targetMax - 1)
            .sort((a, b) => a.height - b.height
                || ((a.column + stageId + variant * 3) % 10) - ((b.column + stageId + variant * 3) % 10));
        if (!candidates.length) throw new Error('无法补足垃圾数量：' + stageId);
        heights[candidates[0].column]++;
    }
    const max = Math.max.apply(null, heights);
    if (max !== targetMax || max > 16) throw new Error('轮廓高度不符合计划：' + stageId);
    const rows = {};
    for (let r = 20 - max; r < 20; r++) {
        const level = 20 - r;
        let line = '';
        for (let c = 0; c < 10; c++) line += heights[c] >= level ? '#' : '.';
        if (line.indexOf('#') >= 0) rows[String(r)] = line;
    }
    return rows;
}

function stats(rows) {
    const lines = Object.values(rows);
    return {
        minLines: lines.length,
        garbageCount: lines.reduce((n, line) => n + line.split('').filter((c) => c === '#').length, 0),
    };
}

function coinThreshold(chapterIndex, local) {
    const base = 24 + Math.floor(chapterIndex / 6);
    return base + (local === 10 ? 2 : local >= 6 ? 1 : 0);
}

