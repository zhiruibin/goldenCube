function themedArtGrid(stageId, art, supportName) {
    const local = ((Number(stageId) - 1) % 10) + 1;
    const topRow = local >= 8 ? 6 : 7;
    const expectedArtRows = local >= 8 ? 10 : 9;
    if (!Array.isArray(art) || art.length !== expectedArtRows) {
        throw new Error('主题主体行数错误：' + stageId + '，期望 ' + expectedArtRows);
    }
    const support = Array.isArray(supportName)
        ? supportName
        : (THEME_SUPPORTS[supportName] || THEME_SUPPORTS.stand);
    if (support.length !== 5 || support.some((line) => !/^[.#]{10}$/.test(line))) {
        throw new Error('主题承托非法：' + stageId);
    }
    return { topRow, lines: art.concat(support) };
}

