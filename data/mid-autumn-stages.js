const STAGES = STAGE_DEFS.map((def, index) => {
    const rows = {};
    def[3].forEach((row, rowIndex) => {
        if (row.indexOf('#') >= 0) rows[String(14 + rowIndex)] = row;
    });
    return {
        id: index + 1,
        title: def[0] + '，' + def[1],
        line1: def[0],
        line2: def[1],
        themeId: 'midAutumn',
        dropIntervalMs: Math.max(820, 1150 - index * 18),
        firstPiece: def[2],
        rows,
    };
});

function getStage(id) {
    return STAGES.find((stage) => stage.id === Number(id)) || null;
}

function getClearedIds() {
    try {
        const value = wx.getStorageSync(PROGRESS_KEY);
        return Array.isArray(value) ? value.map(Number).filter(Boolean) : [];
    } catch (e) { return []; }
}

function getProgress() {
    const ids = Array.from(new Set(getClearedIds()))
        .filter((id) => id >= 1 && id <= TOTAL_STAGE_COUNT);
    return { cleared: ids.length, total: TOTAL_STAGE_COUNT };
}

function markCleared(id) {
    const stageId = Number(id);
    const ids = getClearedIds();
    const first = ids.indexOf(stageId) < 0;
    if (first) {
        ids.push(stageId);
        try { wx.setStorageSync(PROGRESS_KEY, ids); } catch (e) { /* ignore */ }
    }
    const progress = getProgress();
    let badge = { awarded: false, first: false };
    if (progress.cleared >= progress.total) {
        try { badge = require('./theme-badges').award(BADGE_ID); } catch (e) { /* ignore */ }
    }
    return { first, clearedIds: ids, progress, badge };
}

module.exports = {
    STAGES, PROGRESS_KEY, TOTAL_STAGE_COUNT, BADGE_ID,
    getStage, getClearedIds, getProgress, markCleared,
};
